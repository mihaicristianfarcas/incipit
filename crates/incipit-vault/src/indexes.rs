//! Small indexes of the vault, and the guide that says how it is laid out, for an agent to read
//! instead of opening every file, as the earlier app's `indexes.ts` and `AGENTS.md` made them.
//! They are made from the vault's documents and links when asked for (the app asks just before an
//! agent runs), so they are never out of date, and are kept in the generated folder
//! (`.incipit/agent/`), not in the vault: they are not the learner's, history leaves them out, and
//! an agent's working copy has them linked in read-only (`Vault::agent_copy`).
//!
//! The paths are the earlier app's, so the guide's text holds:
//!
//! ```text
//! AGENTS.md, CLAUDE.md      the guide (CLAUDE.md imports AGENTS.md)
//! INDEX.md                  the map: counts, recent changes, where to look
//! library/INDEX.md          every book: folder, size, annotations
//! library/<book>/README.md  a book's annotations by place, its sessions with the tutor, the notes
//!                           and concepts from it
//! notes/INDEX.md           every note: folder, type, tags, links out and in
//! concepts/INDEX.md        every concept: summary, how well it is known, cards, books
//! brain/links.tsv          every link: from, to, kind, line
//! brain/unresolved.tsv     links to things that don't exist yet
//! ```
//!
//! The earlier app's book README also listed the book's chapters with their pages and text files;
//! a book's chapters are not kept in the vault here (the book's file is the source), so they are
//! not listed. How well a concept is known is worked out by the app, so it is given in.

use std::collections::HashMap;

use crate::doc::{Doc, DocId};
use crate::fields::{Annotation, Book, Concept};
use crate::graph::Place;
use crate::kind::Kind;
use crate::store::Vault;

/// The guide: what is where, the shape of every document, how to make things for the learner and
/// the rules for agents. `CLAUDE.md` imports it, as Claude Code reads that file and Codex reads
/// this one.
pub const GUIDE: &str = include_str!("templates/AGENTS.md");

/// The file Claude Code reads, which imports the guide.
pub const CLAUDE: &str = "@AGENTS.md\n";

/// What a generated file starts with, apart from the tables of links: edits there are lost.
const HEADER: &str =
    "<!-- Generated by Incipit from the files in this vault. Edits here are overwritten. -->";

/// The most recently changed documents the map lists.
const RECENT: usize = 20;

/// The most characters of a summary in the table of concepts, and of a quote or a request in a
/// book's list of annotations: the earlier app's.
const SUMMARY: usize = 140;
const QUOTE: usize = 90;
const REQUEST: usize = 80;

/// A generated file: its path from the vault's root, and its text.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Generated {
    pub path: String,
    pub text: String,
}

/// A table cell: one line, no `|`.
fn cell(text: &str) -> String {
    text.replace('|', "\\|")
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
}

/// When a document changed, as the maps say it: its `updated` property as it is written, else when
/// its file was last written, as an RFC 3339 time in UTC. A note made in Obsidian has no such
/// property, and would otherwise be listed with no time and last.
fn changed(vault: &Vault, doc: &Doc) -> String {
    match doc.updated().filter(|said| !said.trim().is_empty()) {
        Some(said) => said,
        None => vault
            .changed_at(doc)
            .map(|time| {
                chrono::DateTime::<chrono::Utc>::from(time)
                    .to_rfc3339_opts(chrono::SecondsFormat::Secs, true)
            })
            .unwrap_or_default(),
    }
}

/// A time as `2026-11-10 09:12` (the first sixteen characters of an RFC 3339 time).
fn day(time: &str) -> String {
    time.chars()
        .take(16)
        .collect::<String>()
        .replacen('T', " ", 1)
}

fn first(text: &str, most: usize) -> String {
    text.chars().take(most).collect()
}

/// A document's path as a link target (without `.md`).
fn target_of(doc: &Doc) -> String {
    let path = doc.path().as_str();
    path.strip_suffix(".md").unwrap_or(path).to_owned()
}

fn file_text(path: &str, text: &str) -> Generated {
    Generated {
        path: path.to_owned(),
        text: text.to_owned(),
    }
}

/// A generated page: the header, then the text.
fn page(path: &str, text: &str) -> Generated {
    file_text(path, &format!("{HEADER}\n{}\n", text.trim()))
}

/// The folder a book lives in: `library/<folder>/book.md`.
fn folder_of(book: &Doc) -> String {
    book.path()
        .parent()
        .map(|folder| folder.name().to_owned())
        .unwrap_or_default()
}

/// How big a book is, in words.
fn size_of(fields: &Book) -> String {
    match (fields.format.as_deref(), fields.parts) {
        (Some("pdf"), Some(n)) => format!("PDF, {n} pages"),
        (Some(format), Some(n)) => format!("{format}, {n} blocks"),
        (Some("pdf"), None) => "PDF".to_owned(),
        (Some(format), None) => format.to_owned(),
        (None, _) => String::new(),
    }
}

/// Where in a book a document is, for ordering and for saying.
fn place_of(doc: &Doc) -> (f64, String) {
    match doc.source() {
        Some(source) => match (source.page, source.block) {
            (Some(page), _) => (f64::from(page), format!("page {page}")),
            (None, Some(block)) => (f64::from(block), format!("block {block}")),
            (None, None) => (0.0, "somewhere".to_owned()),
        },
        None => (0.0, "somewhere".to_owned()),
    }
}

/// The links of every document: `(from, to path or target, kind, line)` for those that reach
/// something, and `(from, target, line)` for those that reach nothing.
struct Edges {
    resolved: Vec<(String, String, String, usize)>,
    unresolved: Vec<(String, String, usize)>,
    /// Links out of and into each document, not counting the concepts a document is about.
    out: HashMap<DocId, usize>,
    into: HashMap<DocId, usize>,
}

fn edges_of(vault: &Vault, docs: &[Doc]) -> Edges {
    let mut edges = Edges {
        resolved: Vec::new(),
        unresolved: Vec::new(),
        out: HashMap::new(),
        into: HashMap::new(),
    };
    let paths: HashMap<&DocId, &str> = docs.iter().map(|d| (d.id(), d.path().as_str())).collect();
    for doc in docs {
        let from = doc.path().as_str();
        for outlink in vault.outlinks(doc.id()) {
            let (kind, about_concepts) = match &outlink.place {
                Place::Body if outlink.link.embed => ("embed".to_owned(), false),
                Place::Body => ("link".to_owned(), false),
                Place::Property(key) if key == "concepts" => ("mentions".to_owned(), true),
                Place::Property(key) => (key.clone(), false),
            };
            let line = match outlink.place {
                Place::Body => outlink.link.line,
                Place::Property(_) => 1,
            };
            let target = outlink
                .to
                .as_ref()
                .and_then(|to| paths.get(to).map(|p| (*p).to_owned()))
                .or_else(|| outlink.picture.as_ref().map(|p| p.as_str().to_owned()));
            // A link counts as one out of the document even when it reaches nothing yet, as the
            // earlier app counted it.
            if !about_concepts {
                *edges.out.entry(doc.id().clone()).or_default() += 1;
            }
            match target {
                Some(to) => {
                    if !about_concepts {
                        if let Some(id) = outlink.to.as_ref().filter(|id| *id != doc.id()) {
                            *edges.into.entry(id.clone()).or_default() += 1;
                        }
                    }
                    edges.resolved.push((from.to_owned(), to, kind, line));
                }
                None => edges
                    .unresolved
                    .push((from.to_owned(), outlink.link.target.clone(), line)),
            }
        }
    }
    edges
}

/// The generated files for the vault as it is now: the guide, the map, one index for the notes,
/// the concepts and the library, a page for each book, and the tables of links. `now` is the
/// time, RFC 3339; `mastery` says how well a concept is known, 0 to 1, when it can be told.
pub fn build(vault: &Vault, now: &str, mastery: &dyn Fn(&DocId) -> Option<f64>) -> Vec<Generated> {
    let mut docs: Vec<Doc> = Kind::ALL
        .into_iter()
        .filter(|kind| *kind != Kind::Book)
        .flat_map(|kind| vault.list(Some(kind)))
        .collect();
    docs.sort_by(|a, b| a.path().cmp(b.path()));
    let books = {
        let mut books = vault.list(Some(Kind::Book));
        books.sort_by_key(|b| b.title().to_lowercase());
        books
    };
    let edges = edges_of(vault, &docs);
    let of_kind = |kind: Kind| docs.iter().filter(move |d| d.kind() == kind);
    let mut files = vec![
        file_text("AGENTS.md", GUIDE),
        file_text("CLAUDE.md", CLAUDE),
    ];

    for book in &books {
        files.push(book_page(book, &docs));
    }
    files.push(library_page(&books, &docs));
    files.push(notes_page(
        vault,
        &of_kind(Kind::Note).collect::<Vec<_>>(),
        &edges,
    ));
    files.push(concepts_page(
        &of_kind(Kind::Concept).collect::<Vec<_>>(),
        &of_kind(Kind::Card).collect::<Vec<_>>(),
        &books,
        &edges,
        vault,
        mastery,
    ));
    files.push(links_table(&edges));
    files.push(unresolved_table(&edges));
    files.push(map_page(vault, &docs, &books, &edges, now));
    files
}

fn map_page(vault: &Vault, docs: &[Doc], books: &[Doc], edges: &Edges, now: &str) -> Generated {
    let count = |kind: Kind| docs.iter().filter(|d| d.kind() == kind).count();
    let mut recent: Vec<(String, &Doc)> = docs.iter().map(|d| (changed(vault, d), d)).collect();
    recent.sort_by(|(a, x), (b, y)| b.cmp(a).then(x.path().cmp(y.path())));
    let mut lines = vec![
        "# Vault index".to_owned(),
        String::new(),
        format!("Updated {} (UTC). Conventions are in AGENTS.md.", day(now)),
        String::new(),
        "| what | how many | where |".to_owned(),
        "|---|---|---|".to_owned(),
        format!(
            "| books | {} | [library/INDEX.md](library/INDEX.md), then library/<book>/README.md |",
            books.len()
        ),
        format!(
            "| notes | {} | [notes/INDEX.md](notes/INDEX.md) |",
            count(Kind::Note)
        ),
        format!(
            "| concepts | {} | [concepts/INDEX.md](concepts/INDEX.md) |",
            count(Kind::Concept)
        ),
        format!(
            "| annotations | {} | library/<book>/annotations/, listed in each book's README.md |",
            count(Kind::Annotation)
        ),
        format!(
            "| sessions with the tutor | {} | library/<book>/sessions/, listed in each book's README.md |",
            count(Kind::Session)
        ),
        format!("| flashcards | {} | cards/ |", count(Kind::Card)),
        format!("| kept figures | {} | figures/ |", count(Kind::Figure)),
        format!(
            "| links | {} ({} unresolved) | brain/links.tsv, brain/unresolved.tsv |",
            edges.resolved.len(),
            edges.unresolved.len()
        ),
        String::new(),
        "## Recently changed".to_owned(),
        String::new(),
    ];
    lines.extend(
        recent
            .into_iter()
            .take(RECENT)
            .map(|(time, d)| format!("- {} · {}", day(&time), d.path())),
    );
    page("INDEX.md", &lines.join("\n"))
}

fn library_page(books: &[Doc], docs: &[Doc]) -> Generated {
    let mut lines = vec![
        "# Library".to_owned(),
        String::new(),
        format!(
            "{} book{}. Each folder holds book.md (its record), the book's own file, annotations/, \
             sessions/ and a README.md with the annotations, the sessions and the notes and concepts from it.",
            books.len(),
            if books.len() == 1 { "" } else { "s" }
        ),
        String::new(),
        "| book | author | folder | format | size | annotations | added |".to_owned(),
        "|---|---|---|---|---|---|---|".to_owned(),
    ];
    for book in books {
        let fields = book.fields::<Book>().unwrap_or_default();
        let folder = folder_of(book);
        let annotations = docs
            .iter()
            .filter(|d| d.kind() == Kind::Annotation)
            .filter(|d| d.source().is_some_and(|s| s.book == book.id().as_str()))
            .count();
        lines.push(format!(
            "| {} | {} | [{folder}/]({folder}/README.md) | {} | {} | {} | {} |",
            cell(&book.title()),
            cell(fields.author.as_deref().unwrap_or_default()),
            fields.format.as_deref().unwrap_or_default(),
            size_of(&fields),
            if annotations == 0 {
                String::new()
            } else {
                annotations.to_string()
            },
            book.created()
                .unwrap_or_default()
                .chars()
                .take(10)
                .collect::<String>(),
        ));
    }
    page("library/INDEX.md", &lines.join("\n"))
}

fn book_page(book: &Doc, docs: &[Doc]) -> Generated {
    let fields = book.fields::<Book>().unwrap_or_default();
    let id = book.id().as_str();
    let mine = |kind: Kind| -> Vec<&Doc> {
        docs.iter()
            .filter(|d| d.kind() == kind)
            .filter(|d| d.source().is_some_and(|s| s.book == id))
            .collect()
    };
    let mut lines = vec![format!("# {}", book.title()), String::new()];
    let mut facts = Vec::new();
    if let Some(author) = &fields.author {
        facts.push(format!("by {author}"));
    }
    let size = size_of(&fields);
    if !size.is_empty() {
        facts.push(size);
    }
    facts.push(format!(
        "added {}",
        day(&book.created().unwrap_or_default())
    ));
    if let Some(file) = &fields.file {
        let edition = fields
            .edition
            .as_ref()
            .map(|e| format!(" (edition {e})"))
            .unwrap_or_default();
        facts.push(format!("file `{file}`{edition}"));
    }
    facts.push(format!("book id `{id}`"));
    lines.push(facts.join(" · "));

    let mut annotations = mine(Kind::Annotation);
    annotations.sort_by(|a, b| {
        place_of(a)
            .0
            .total_cmp(&place_of(b).0)
            .then(a.path().cmp(b.path()))
    });
    if !annotations.is_empty() {
        lines.extend([String::new(), "## Annotations".to_owned(), String::new()]);
        for doc in annotations {
            let request = doc
                .fields::<Annotation>()
                .and_then(|a| a.request)
                .filter(|r| !r.trim().is_empty())
                .map(|r| format!(" (“{}”)", first(&cell(&r), REQUEST)))
                .unwrap_or_default();
            let quote = doc.source().and_then(|s| s.quote).unwrap_or_default();
            lines.push(format!(
                "- {} · {}{request} · “{}…” → [[{}]]",
                place_of(doc).1,
                doc.doc_type().unwrap_or("highlight"),
                first(&cell(&quote), QUOTE),
                target_of(doc)
            ));
        }
    }
    let mut sessions = mine(Kind::Session);
    sessions.sort_by_key(|d| d.created());
    if !sessions.is_empty() {
        lines.extend([
            String::new(),
            "## Sessions with the tutor".to_owned(),
            String::new(),
        ]);
        lines.extend(sessions.iter().map(|d| {
            format!(
                "- {} · {} → [[{}]]",
                d.created()
                    .unwrap_or_default()
                    .chars()
                    .take(10)
                    .collect::<String>(),
                cell(&d.title()),
                target_of(d)
            )
        }));
    }
    let from_book: Vec<&Doc> = mine(Kind::Note);
    if !from_book.is_empty() {
        lines.extend([
            String::new(),
            "## Notes from this book".to_owned(),
            String::new(),
        ]);
        lines.extend(from_book.iter().map(|d| {
            let sort = d.doc_type().filter(|t| *t != "note");
            format!(
                "- [[{}]]{}",
                d.title(),
                sort.map(|t| format!(" ({t})")).unwrap_or_default()
            )
        }));
    }
    let concepts: Vec<&Doc> = docs
        .iter()
        .filter(|d| d.kind() == Kind::Concept)
        .filter(|d| {
            d.fields::<Concept>()
                .is_some_and(|c| c.sources.iter().any(|s| s.book == id))
        })
        .collect();
    if !concepts.is_empty() {
        lines.extend([String::new(), "## Concepts".to_owned(), String::new()]);
        lines.extend(concepts.iter().map(|d| {
            let summary = d.fields::<Concept>().map(|c| c.summary).unwrap_or_default();
            format!("- [[{}]] — {}", d.title(), cell(&summary))
        }));
    }
    page(
        &format!("library/{}/README.md", folder_of(book)),
        &lines.join("\n"),
    )
}

fn notes_page(vault: &Vault, notes: &[&Doc], edges: &Edges) -> Generated {
    let mut lines = vec![
        "# Notes".to_owned(),
        String::new(),
        format!(
            "{} note{}. The file name is the title. \"out\" and \"in\" count links (in: backlinks; see brain/links.tsv).",
            notes.len(),
            if notes.len() == 1 { "" } else { "s" }
        ),
        String::new(),
        "| note | folder | type | tags | out | in | updated |".to_owned(),
        "|---|---|---|---|---|---|---|".to_owned(),
    ];
    let count = |map: &HashMap<DocId, usize>, id: &DocId| {
        map.get(id)
            .filter(|n| **n > 0)
            .map(ToString::to_string)
            .unwrap_or_default()
    };
    for note in notes {
        let folder = note.folder();
        lines.push(format!(
            "| [[{}]] | {} | {} | {} | {} | {} | {} |",
            note.title(),
            cell(&folder),
            note.doc_type().unwrap_or("note"),
            cell(&note.all_tags().join(", ")),
            count(&edges.out, note.id()),
            count(&edges.into, note.id()),
            day(&changed(vault, note)),
        ));
    }
    page("notes/INDEX.md", &lines.join("\n"))
}

fn concepts_page(
    concepts: &[&Doc],
    cards: &[&Doc],
    books: &[Doc],
    edges: &Edges,
    vault: &Vault,
    mastery: &dyn Fn(&DocId) -> Option<f64>,
) -> Generated {
    let mut lines = vec![
        "# Concepts".to_owned(),
        String::new(),
        format!(
            "{} concept{}. Mastery is the predicted recall of the concept's cards right now (or the best explain-it-back score).",
            concepts.len(),
            if concepts.len() == 1 { "" } else { "s" }
        ),
        String::new(),
        "| concept | id | summary | mastery | cards | books | in |".to_owned(),
        "|---|---|---|---|---|---|---|".to_owned(),
    ];
    let mut sorted: Vec<&&Doc> = concepts.iter().collect();
    sorted.sort_by_key(|c| c.title().to_lowercase());
    for concept in sorted {
        let fields = concept.fields::<Concept>().unwrap_or_default();
        let known = mastery(concept.id())
            .map(|m| format!("{}%", (m * 100.0).round()))
            .unwrap_or_default();
        let about = vault
            .backlinks(concept.id())
            .iter()
            .filter(|b| matches!(&b.place, Place::Property(key) if key == "concepts"))
            .filter(|b| cards.iter().any(|c| c.id() == &b.from))
            .map(|b| b.from.clone())
            .collect::<std::collections::HashSet<_>>()
            .len();
        let mut from: Vec<String> = Vec::new();
        for source in &fields.sources {
            if let Some(title) = books
                .iter()
                .find(|b| b.id().as_str() == source.book)
                .map(Doc::title)
            {
                if !from.contains(&title) {
                    from.push(title);
                }
            }
        }
        lines.push(format!(
            "| [[{}]] | `{}` | {} | {} | {} | {} | {} |",
            concept.title(),
            concept.id(),
            first(&cell(&fields.summary), SUMMARY),
            known,
            if about == 0 {
                String::new()
            } else {
                about.to_string()
            },
            cell(&from.join(", ")),
            edges
                .into
                .get(concept.id())
                .filter(|n| **n > 0)
                .map(ToString::to_string)
                .unwrap_or_default(),
        ));
    }
    page("concepts/INDEX.md", &lines.join("\n"))
}

/// A table of tab-separated values, with no header comment (a tool reads it).
fn tsv(path: &str, header: &str, rows: impl Iterator<Item = String>) -> Generated {
    let mut text = format!("{header}\n");
    for row in rows {
        text.push_str(&row);
        text.push('\n');
    }
    file_text(path, &text)
}

/// A field of a table of tab-separated values: one line, no tab.
fn field(text: &str) -> String {
    text.replace(['\t', '\n', '\r'], " ")
}

fn links_table(edges: &Edges) -> Generated {
    tsv(
        "brain/links.tsv",
        "from\tto\tkind\tline",
        edges.resolved.iter().map(|(from, to, kind, line)| {
            format!("{}\t{}\t{kind}\t{line}", field(from), field(to))
        }),
    )
}

fn unresolved_table(edges: &Edges) -> Generated {
    tsv(
        "brain/unresolved.tsv",
        "from\ttarget\tline",
        edges
            .unresolved
            .iter()
            .map(|(from, target, line)| format!("{}\t{}\t{line}", field(from), field(target))),
    )
}

